function normalize(value: string) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim().replace(/\s+/g, ' ');
}

function hash(value: string) {
  let h = 2166136261;
  for (let i = 0; i < value.length; i += 1) {
    h ^= value.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

function pick(key: PoolKey, seed: string) {
  const list = pool[key];
  return list[hash(seed) % list.length];
}

export function dishImage(category: string, name: string) {
  const key = normalize(name);
  const exactKey = exact[key];
  if (exactKey) return pick(exactKey, name);

  for (const [pattern, poolKey] of rules) {
    if (pattern.test(key)) return pick(poolKey, name);
  }

  const fromCategory = categoryPool[category];
  if (fromCategory) return pick(fromCategory, category + name);
  return pick('fallback', name);
}
